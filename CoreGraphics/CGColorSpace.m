CFDataRef CGColorSpaceCopyICCData(CGColorSpaceRef space)
{
    (void) space;
    fprintf(stderr, "cg_colorspace_icc_v1 CopyICCData space=%p bytes=%u\n",
            (void *) space, (unsigned) sizeof(kSRGB_ICC));
    fflush(stderr);
    return CFDataCreate(kCFAllocatorDefault, kSRGB_ICC, (CFIndex) sizeof(kSRGB_ICC));
}

CFStringRef CGColorSpaceCopyName(CGColorSpaceRef space)
{
    (void) space;
    return CFStringCreateCopy(kCFAllocatorDefault, kCGColorSpaceSRGB);
}

CGColorSpaceRef CGDisplayCopyColorSpace(uint32_t display)
{
    (void) display;
    return CGColorSpaceCreateWithName(kCGColorSpaceSRGB);
}
